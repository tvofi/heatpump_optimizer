"""R10-CONFIG-FLOW-TEXT-VERIFY -- every user-visible config- and options-flow
string, and the record of each behavioural claim's verdict.

The method is round 4's D6 claims record (dev/audit/rounds/round4/D6/claims.py,
re-truthed by #3513): one row per claim, its evidence, a verdict in
{true, false, stale, unverifiable, no-claim} and, where false or stale, the
corrected text. The figures the corrected text quotes are pinned by
tests/doc_claims.py's check_flow_text_claims; everything else is prose-only.

RUN (from the repository root):
    python3 dev/audit/rounds/round10/D6/flow_claims.py enumerate
        # every leaf under config, options and selector in strings.json and
        # each translation, "<catalogue>\\t<dotted key>\\t<text>", then one
        # count line per catalogue; the claim set is the distinct English
        # texts of 40 characters or more ("distinct" prints those)
    python3 dev/audit/rounds/round10/D6/flow_claims.py distinct
    python3 dev/audit/rounds/round10/D6/flow_claims.py render
        # flow-claims.json -> flow-claims.md
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(".")
PKG = ROOT / "custom_components" / "heatpump_optimizer"
HERE = ROOT / "dev" / "audit" / "rounds" / "round10" / "D6"
TOPS = ("config", "options", "selector")
MIN_CHARS = 40


def catalogues() -> dict[str, dict]:
    out = {"strings": json.loads((PKG / "strings.json").read_text())}
    for path in sorted((PKG / "translations").glob("*.json")):
        out[path.stem] = json.loads(path.read_text())
    return out


def leaves(node, path=()):
    if isinstance(node, dict):
        for key, value in node.items():
            yield from leaves(value, (*path, key))
    else:
        yield ".".join(path), node


def flow_leaves(texts: dict) -> list[tuple[str, str]]:
    return [(k, v) for top in TOPS for k, v in leaves(texts.get(top, {}), (top,))]


def distinct(texts: dict) -> dict[str, list[str]]:
    """``{text: [keys]}`` for every English flow text of MIN_CHARS or more."""
    out: dict[str, list[str]] = {}
    for key, text in flow_leaves(texts):
        if len(text) >= MIN_CHARS:
            out.setdefault(text, []).append(key)
    return out


def render() -> str:
    rows = json.loads((HERE / "flow-claims.json").read_text())
    lines = [
        "# Config- and options-flow text: claims against code (R10-CONFIG-FLOW-TEXT-VERIFY)",
        "",
        "Generated by `python3 dev/audit/rounds/round10/D6/flow_claims.py render` from "
        "flow-claims.json. One row per distinct English flow text of "
        f"{MIN_CHARS} characters or more (`distinct`); `keys` counts the strings.json keys "
        "carrying that text. Evidence is at the merge base named in flow-claims.json. "
        "`pinned` names the tests/doc_claims.py arm holding a corrected figure; "
        "every other row is prose-only.",
        "",
        "| key | keys | claim | evidence | verdict | pinned | correction |",
        "|---|---|---|---|---|---|---|",
    ]
    cell = lambda s: str(s).replace("|", "\\|").replace("\n", " / ")
    for row in rows["rows"]:
        lines.append("| `{}` | {} | {} | {} | **{}** | {} | {} |".format(
            row["key"], row["n_keys"], cell(row["claim"]),
            "<br>".join(f"`{e}`" for e in row["evidence"]), row["verdict"],
            row.get("pinned", ""), cell(row.get("correction", ""))))
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "enumerate"
    if cmd == "enumerate":
        cats = catalogues()
        for name, texts in cats.items():
            for key, text in flow_leaves(texts):
                print(f"{name}\t{key}\t{text}")
        for name, texts in cats.items():
            print(f"# {name}: {len(flow_leaves(texts))} flow strings")
        return 0
    if cmd == "distinct":
        found = distinct(catalogues()["strings"])
        for text, keys in found.items():
            print(f"{keys[0]}\t{len(keys)}\t{text}")
        print(f"# {len(found)} distinct English flow texts of {MIN_CHARS}+ characters")
        return 0
    if cmd == "render":
        (HERE / "flow-claims.md").write_text(render())
        return 0
    print(f"unknown command {cmd!r}", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
