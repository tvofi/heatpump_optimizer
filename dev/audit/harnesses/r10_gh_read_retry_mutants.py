def _group_cuts(body: str) -> list[list[int]]:
    """Per group of a regex body (and the whole body): its open, each `|`, its close."""
    levels: list[list[int]] = [[-1]]
    spans: list[list[int]] = []
    k, cls = 0, False
    while k < len(body):
        ch = body[k]
        if ch == "\\":
            k += 2
            continue
        if cls:
            cls = ch != "]"
        elif ch == "[":
            cls = True
        elif ch == "(":
            levels.append([k + (2 if body.startswith("(?:", k) else 0)])
        elif ch == "|":
            levels[-1].append(k)
        elif ch == ")":
            spans.append(levels.pop() + [k])
        k += 1
    spans.append(levels.pop() + [len(body)])
    return spans


def _regex_mutants(body: str) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for cuts in _group_cuts(body):
        if len(cuts) > 2:
            parts = [(a + 1, b) for a, b in zip(cuts, cuts[1:])]
            for k, (a, b) in enumerate(parts):
                keep = [body[x:y] for j, (x, y) in enumerate(parts) if j != k]
                lo, hi = parts[0][0], parts[-1][1]
                out.append((f"re alt -{body[a:b]!r}", body[:lo] + "|".join(keep) + body[hi:]))
    k = 0
    while k < len(body):
        ch = body[k]
        if ch == "\\":
            k += 2
            continue
        if ch in "^$":
            out.append((f"re anch {ch}@{k}", body[:k] + body[k + 1:]))
        elif ch in "?*+" and k and body[k - 1] != "(":
            out.append((f"re quant {ch}@{k}", body[:k] + body[k + 1:]))
        elif ch == "{":
            j = body.index("}", k)
            out.append((f"re quant {body[k:j + 1]}", body[:k] + body[j + 1:]))
        k += 1
    return out


def py_mutants(lines: list[str]) -> list[tuple[int, int, str, list[str]]]:
    """(first line, line after, rule, replacement lines) for every rule application."""
    reg = py_region(lines)
    src = "\n".join(lines)
    tree = ast.parse(src)
    skip_strings: set[tuple[int, int]] = set()  # docstrings and f-strings, by (row, col)
    regexes: set[tuple[int, int]] = set()
    for node in ast.walk(tree):
        body = getattr(node, "body", None)
        if isinstance(body, list) and body and isinstance(body[0], ast.Expr) \
                and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str):
            skip_strings.add((body[0].lineno - 1, body[0].col_offset))
        if isinstance(node, ast.JoinedStr):
            skip_strings.add((node.lineno - 1, node.col_offset))
        if (isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "compile"
                and node.args and isinstance(node.args[0], ast.Constant)):
            regexes.add((node.args[0].lineno - 1, node.args[0].col_offset))
    notes: list[tuple[tuple[int, int], tuple[int, int]]] = []  # annotations: no behaviour
    for node in ast.walk(tree):
        for ann in ([node.returns] if isinstance(node, ast.FunctionDef) else []) + \
                ([node.annotation] if isinstance(node, (ast.arg, ast.AnnAssign)) else []):
            if ann is not None:
                notes.append(((ann.lineno - 1, ann.col_offset), (ann.end_lineno - 1, ann.end_col_offset)))

    def annotated(row: int, col: int) -> bool:
        return any(a <= (row, col) < b for a, b in notes)
    out: list[tuple[int, int, str, list[str]]] = []

    def put(row: int, a: int, b: int, rule: str, text: str) -> None:
        new = lines[row][:a] + text + lines[row][b:]
        if new != lines[row] and not annotated(row, a):
            out.append((row, row + 1, rule, [new]))
    toks = [t for t in tokenize.generate_tokens(io.StringIO(src).readline)
            if t.start[0] - 1 in reg and t.start[0] == t.end[0]]
    for n, t in enumerate(toks):
        row, (a, b), v = t.start[0] - 1, (t.start[1], t.end[1]), t.string
        prev = toks[n - 1] if n else None
        nxt = toks[n + 1] if n + 1 < len(toks) else None
        if t.type == tokenize.NUMBER:
            if "." in v:
                put(row, a, b, f"num {v}->+1", repr(float(v) + 1))
            else:
                k = int(v)
                for w in ([k - 1] if k > 0 else []) + [k + 1, 999]:
                    put(row, a, b, f"num {k}->{w}", str(w))
        elif t.type == tokenize.OP and v in CMP:
            for op in CMP:
                if op != v:
                    put(row, a, b, f"cmp {v}->{op}", op)
        elif t.type == tokenize.NAME and v in ("and", "or"):
            put(row, a, b, f"bool {v}", "or" if v == "and" else "and")
        elif t.type == tokenize.NAME and v == "not":
            put(row, a, nxt.start[1] if nxt and nxt.start[0] == t.start[0] else b, "not -not", "")
        elif t.type == tokenize.NAME and v == "in" and not (prev and prev.string == "not"):
            line_toks = [x.string for x in toks if x.start[0] == t.start[0] and x.start[1] < a]
            if "for" not in line_toks:
                put(row, a, b, "not +in->not in", "not in")
        elif t.type == tokenize.NAME and v in ("True", "False"):
            put(row, a, b, f"const {v}", "False" if v == "True" else "True")
        elif t.type == tokenize.NAME and v == "None":
            put(row, a, b, "const None->0.0", "0.0")
        elif t.type == tokenize.NAME and v in METH and prev and prev.string == ".":
            if METH[v]:
                put(row, a, b, f"meth {v}->{METH[v]}", METH[v])
            elif nxt and nxt.string == "(" and toks[n + 2].string == ")":
                put(row, prev.start[1], toks[n + 2].end[1], f"meth -.{v}()", "")
        elif t.type == tokenize.STRING and (row, a) not in skip_strings:
            pre = re.match(r"[a-zA-Z]*", v).group(0)
            if "f" in pre.lower() or v[len(pre):].startswith(('"""', "\'\'\'")):
                continue
            q, body = v[len(pre)], v[len(pre) + 1:-1]
            if (row, a) in regexes:
                for rule, mut in _regex_mutants(body):
                    put(row, a, b, rule, pre + q + mut + q)
                continue
            value = ast.literal_eval(v)
            if not isinstance(value, str):
                continue
            put(row, a, b, "str ->''" if value else "str ''->x", pre + q + ("" if value else "x") + q)
            if re.fullmatch(r"[A-Za-z]+( [A-Za-z]+)+", value):
                words = value.split(" ")
                for k in range(len(words)):
                    put(row, a, b, f"str word -{words[k]}", pre + q + " ".join(words[:k] + words[k + 1:]) + q)
    for node in ast.walk(tree):
        if not hasattr(node, "lineno") or node.lineno - 1 not in reg:
            continue
        row = node.lineno - 1
        if isinstance(node, (ast.If, ast.IfExp)) and node.test.lineno == node.test.end_lineno:
            tr = node.test.lineno - 1
            seg = ast.get_source_segment(src, node.test)
            put(tr, node.test.col_offset, node.test.end_col_offset, "if not", f"not ({seg})")
        if isinstance(node, ast.Tuple) and node.lineno == node.end_lineno and len(node.elts) > 1:
            for k, e in enumerate(node.elts):
                rest = [ast.get_source_segment(src, x) for j, x in enumerate(node.elts) if j != k]
                lo, hi = node.elts[0].col_offset, node.elts[-1].end_col_offset
                put(row, lo, hi, f"elt -{ast.get_source_segment(src, e)}", ", ".join(rest) + ("," if len(rest) == 1 else ""))
        if isinstance(node, ast.stmt) and not isinstance(node, (ast.FunctionDef, ast.If, ast.For, ast.While,
                                                                 ast.With, ast.Try, ast.ClassDef)):
            if isinstance(node, (ast.Expr, ast.Pass)) and not isinstance(getattr(node, "value", None), ast.Call):
                continue  # a docstring, or a `pass` already
            indent = lines[row][:len(lines[row]) - len(lines[row].lstrip())]
            out.append((row, node.end_lineno, "del", [indent + "pass"]))
    return out


#: No bytecode is written or read: a mutant written within the second of the
#: last one, at the same size, would run that one's stale `__pycache__` entry
#: (CPython checks only mtime and size), which flipped P121's verdict between
#: two runs before this was set.
NO_PYC = {**__import__("os").environ, "PYTHONDONTWRITEBYTECODE": "1"}


def tier(tree: Path, argv: list[str]) -> tuple[int, str]:
    argv = [argv[0], "-B", *argv[1:]] if argv[0] == "python3" else argv
    p = subprocess.run(argv, cwd=tree, capture_output=True, text=True, env=NO_PYC)
    out = p.stdout.splitlines()
    summary = next((l for l in reversed(out) if "self-test" in l), "no summary line")
    fails = [l.strip()[5:] for l in out if l.strip().startswith("FAIL ")]
    behaviour = [f for f in fails if not f.startswith(PRECONDITION)]
    if p.returncode and not fails:  # a crash, or record_row's summary-only failure
        return p.returncode, summary + "; " + (p.stderr.strip().splitlines() or ["no stderr"])[-1]
    rc = p.returncode if behaviour else 0  # source-text checks alone kill nothing
    shown = behaviour or fails
    return rc, summary + ("; first FAIL: " + shown[0] if shown else "") + ("" if behaviour or not fails else "; PRECONDITION ONLY")


def py_selftest(tree: Path) -> tuple[int, str]:
    rc, summary = tier(tree, PY_TIER1)
    if rc:
        return rc, "tier 1: " + summary
    for argv in PY_TIER2:
        rc, summary = tier(tree, argv)
        if rc:
            return rc, f"tier 2 ({argv[1]}): {summary}"
    return 0, "both tiers pass: " + summary


# ------------------------------------------------------------------ the seams
SEAM_PY = ("tools/audit/seat/merge_train.py", "tools/audit/seat/queue_pre_flight.py",
           "tools/audit/seat/record_row.py")
#: The call routes that are Train.run, which Train._reads_retried wraps.
TRAIN_RUN = ("self.run", "self.out", "self.ok", "self.t.run", "self.t.out", "self.t.ok")


def _argv_of(call: ast.Call) -> list[str] | None:
    """The call's literal argv: a list first argument, or `out`/`ok`'s varargs."""
    elts = None
    if call.args and isinstance(call.args[0], ast.List):
        elts = call.args[0].elts
    elif isinstance(call.func, ast.Attribute) and call.func.attr in ("out", "ok"):
        elts = call.args
    if not elts:
        return None
    return [e.value if isinstance(e, ast.Constant) and isinstance(e.value, str) else "X" for e in elts]


def _wrapped(root: Path) -> tuple[bool, bool]:
    """The census's preconditions, read off the tree it judges: Train.__init__
    assigns `self.run = self._reads_retried(...)`, and `_api` calls `gh_read.retry`."""
    def calls(tree, owner, attr):
        return any(isinstance(f, ast.FunctionDef) and f.name == owner
                   and any(isinstance(c, ast.Call) and getattr(c.func, "attr", "") == attr for c in ast.walk(f))
                   for f in ast.walk(tree))
    mt = ast.parse((root / SEAM_PY[0]).read_text())
    rr = ast.parse((root / SEAM_PY[2]).read_text())
    return calls(mt, "__init__", "_reads_retried"), calls(rr, "_api", "retry")


def seams(root: Path = ROOT) -> int:
    sys.path.insert(0, str(ROOT / "tools/audit/seat"))
    import gh_read
    train_wrapped, api_wrapped = _wrapped(root)
    print(f"PRECONDITION Train.run wrapped={train_wrapped} _api retried={api_wrapped}")
    bad = 0
    for rel in SEAM_PY:
        src = (root / rel).read_text()
        tree = ast.parse(src)
        tests: set[int] = set()
        for f in ast.walk(tree):
            if isinstance(f, ast.FunctionDef) and "self_test" in f.name:
                tests.update(range(f.lineno, f.end_lineno + 1))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call) or node.lineno in tests:
                continue
            fn = ast.get_source_segment(src, node.func)
            argv = _argv_of(node)
            if fn.endswith("urlopen"):
                inside = [f.name for f in ast.walk(tree) if isinstance(f, ast.FunctionDef)
                          and f.lineno <= node.lineno <= f.end_lineno]
                ok = "_api" in inside and api_wrapped
                route = "read: retried, `_api`'s attempt under gh_read.retry" if ok else "read: NOT RETRIED"
            elif argv and argv[:3] == ["gh", "api", "graphql"]:
                # is_read refuses every graphql call: a mutation is sent the same way.
                ok = src.split("\n")[node.lineno - 1].lstrip().startswith("self.log(")
                route = ("graphql query, log-only: its answer is printed and stops nothing; not retried"
                         if ok else "graphql: NOT RETRIED and not log-only")
            elif argv and argv[0] == "gh":
                if not gh_read.is_read(argv):
                    ok, route = True, "write or local: never retried"
                elif fn in TRAIN_RUN and train_wrapped:
                    ok, route = True, f"read: retried, {fn} is Train._reads_retried"
                else:
                    ok, route = False, f"read: NOT RETRIED ({fn})"
            elif argv and argv[0] == "git" and any(a in ("fetch", "push", "ls-remote") for a in argv[1:3]):
                ok, route = True, "git transport: a distinct seam, not an API read"
            else:
                continue
            bad += not ok
            print(f"{rel}:{node.lineno}\t{' '.join(argv or [fn])[:70]}\t{route}")
    lines = (root / TARGET).read_text().split("\n")
    stop = next(i for i, l in enumerate(lines) if l.startswith('if [ "${1:-}" != "--self-test" ]'))
    head = re.compile(r"^(\w+)\(\) \{")
    fn = ""
    for i, l in enumerate(lines[:stop]):
        m = head.match(l)
        fn = m.group(1) if m else ("" if l == "}" else fn)
        if l.lstrip().startswith("#") or not re.search(r"\bgh api\b|\bcurl\b|\bgit fetch\b|\bgh_read\b|\bread_with\b", l):
            continue
        if re.search(r"\b(gh_read|read_with) \w+ ", l) or fn == "curl_get":
            route = "read: retried, read_with" if fn != "curl_get" else "read: the fetcher read_with retries"
        elif fn in ("read_with", "gh_read") or l.startswith(("gh_read() {", "read_with() {")):
            route = "the loop itself"
        elif re.search(r"curl .*-X (POST|DELETE)", l):
            route = "write: never retried"
        elif "git fetch" in l:
            route = "git transport: a distinct seam, not an API read"
        else:
            route = "read: NOT RETRIED"
            bad += 1
        print(f"{TARGET}:{i + 1}\t{l.strip()[:70]}\t{route}")
    print(f"SEAMS unretried_reads={bad}")
    return 1 if bad else 0


def selftest(tree: Path) -> tuple[int, str]:
    p = subprocess.run(["bash", TARGET, "--self-test"], cwd=tree, capture_output=True, text=True)
    summary = next((l for l in reversed(p.stdout.splitlines()) if "self-test:" in l), "no summary line")
    fails = [l[5:] for l in p.stdout.splitlines() if l.startswith("FAIL ")]
    behaviour = [f for f in fails if not f.startswith(PRECONDITION)]
    rc = p.returncode if behaviour or not fails else 0  # source-text checks alone kill nothing
    shown = behaviour or fails
    return rc, summary + ("; first FAIL: " + shown[0] if shown else "") + ("" if behaviour or not fails else "; PRECONDITION ONLY")


def main(argv: list[str]) -> int:
    if "--seams" in argv:  # `--seams DIR` judges another tree (the base: the null control)
        k = argv.index("--seams")
        return seams(Path(argv[k + 1]) if k + 1 < len(argv) else ROOT)
    jobs = 4
    if "--jobs" in argv:
        k = argv.index("--jobs"); jobs = int(argv[k + 1]); del argv[k:k + 2]
    bases = {TARGET: (ROOT / TARGET).read_text(), PY_TARGET: (ROOT / PY_TARGET).read_text()}
    lines = {t: b.split("\n") for t, b in bases.items()}
    # Every mutant as (target, first line, line after, rule, replacement lines).
    table: dict[str, tuple[str, int, int, str, list[str]]] = {"M0": (TARGET, -1, -1, "null", [])}
    for n, (i, rule, new) in enumerate(mutants(lines[TARGET]), start=1):
        table[f"M{n}"] = (TARGET, i, i + 1, rule, [] if rule == "del" else [new])
    table["P0"] = (PY_TARGET, -1, -1, "null", [])
    for n, (i, j, rule, new) in enumerate(py_mutants(lines[PY_TARGET]), start=1):
        table[f"P{n}"] = (PY_TARGET, i, j, rule, new)
    generated = {(lines[t][i], "\n".join(new)) for t, i, j, _, new in table.values() if i >= 0 and j == i + 1}
    stale = [k for k in EQUIVALENT if k not in generated]
    if stale:  # an entry no rule generates any more would excuse nothing, silently
        print(f"EQUIVALENT entries no rule generates: {stale}")
        return 1
    names = [a for a in argv if not a.startswith("--")] or list(table)
    if "--list" in argv:
        for name in names:
            t, i, j, rule, new = table[name]
            print(f"{name}\t{t}:{i + 1 if i >= 0 else '-'}\t{rule}\t{new!r}")
        return 0
    trees: Queue[Path] = Queue()
    tmp = Path(tempfile.mkdtemp(prefix="ghretry-mut-"))
    for k in range(jobs):
        w = tmp / f"w{k}"
        subprocess.run(["git", "worktree", "add", "--detach", "-q", str(w), "HEAD"], cwd=ROOT, check=True)
        for cache in w.rglob("__pycache__"):
            shutil.rmtree(cache)
        trees.put(w)

    def one(name: str) -> tuple[str, str]:
        t, i, j, rule, new = table[name]
        w = trees.get()
        try:
            text = lines[t][:]
            if i >= 0:
                text[i:j] = new
            (w / t).write_text("\n".join(text))
            rc, summary = (selftest if t == TARGET else py_selftest)(w)
            (w / t).write_text(bases[t])
        finally:
            trees.put(w)
        old = "\n".join(lines[t][i:j]) if i >= 0 else ""
        mutated = "\n".join(new)
        where = "" if i < 0 else f" {t.rsplit('/', 1)[-1]} l.{i + 1} {rule}: {old.strip()!r}" + (
            "" if rule == "del" and t == TARGET else f" -> {mutated.strip()!r}")
        if i < 0:
            verdict = "NULL-OK" if rc == 0 else "NULL-FAILED"
        elif rc != 0:
            verdict = "KILLED"
        elif (old, mutated) in EQUIVALENT:
            verdict = "EQUIVALENT (" + EQUIVALENT[(old, mutated)] + ")"
        else:
            verdict = "SURVIVED"
        return name, f"{name} {verdict}{where} | rc={rc} {summary}"

    try:
        with ThreadPoolExecutor(jobs) as ex:
            results = dict(ex.map(one, names))
    finally:
        for k in range(jobs):
            subprocess.run(["git", "worktree", "remove", "--force", str(tmp / f"w{k}")], cwd=ROOT)
        shutil.rmtree(tmp, ignore_errors=True)
    for name in names:
        print(results[name])
    rows = [results[n] for n in names if n not in ("M0", "P0")]
    k = sum(" KILLED" in r for r in rows)
    e = sum(" EQUIVALENT" in r for r in rows)
    sv = sum(" SURVIVED" in r for r in rows)
    print(f"RESULT mutants={len(rows)} killed={k} equivalent={e} survivors={sv}")
    null_bad = any("NULL-FAILED" in results[n] for n in ("M0", "P0") if n in results)
    return 1 if sv or null_bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
