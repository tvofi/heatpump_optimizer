def region(lines: list[str]) -> range:
    start = next(i for i, l in enumerate(lines) if l.startswith("READ_TRIES="))
    after = next(i for i in range(start, len(lines)) if lines[i].startswith("check_pr() {"))
    end = max(i for i in range(start, after) if lines[i] == "}")
    return range(start, end + 1)


def code(line: str) -> str:
    """The line up to an inline comment: a ` # ` with no quote open before it."""
    for m in re.finditer(r"\s#\s", line):
        pre = line[:m.start()]
        if pre.count("'") % 2 == 0 and pre.count('"') % 2 == 0:
            return pre
    return line


def mutants(lines: list[str]) -> list[tuple[int, str, str]]:
    """(line index, rule, mutated line) for every rule application in the region."""
    out: list[tuple[int, str, str]] = []
    for i in region(lines):
        line = code(lines[i])
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        for m in NUM.finditer(line):
            n = int(m.group(1))
            for v in ([n - 1] if n > 0 else []) + [n + 1, 999]:
                out.append((i, f"num {n}->{v}", lines[i][:m.start()] + str(v) + lines[i][m.end():]))
        for m in re.finditer(r"(?<=\s)-(ge|gt|le|lt|eq|ne)(?=\s)", line):
            for op in REL:
                if op != m.group(0):
                    out.append((i, f"rel {m.group(0)}->{op}", lines[i][:m.start()] + op + lines[i][m.end():]))
        for m in re.finditer(r'"\$\w+"(?= -(?:ge|gt|le|lt|eq|ne) )|(?<=-(?:ge|gt|le|lt|eq|ne) )"\$\w+"', line):
            out.append((i, f"opnd {m.group(0)}->999", lines[i][:m.start()] + "999" + lines[i][m.end():]))
        for m in re.finditer(r"\|\||&&", line):
            alt = "&&" if m.group(0) == "||" else "||"
            out.append((i, f"or {m.group(0)}->{alt}", lines[i][:m.start()] + alt + lines[i][m.end():]))
        for m in re.finditer(r"\bif ! ", line):
            out.append((i, "not", lines[i][:m.start()] + "if " + lines[i][m.end():]))
        for m in re.finditer(r"\breturn(?= ;|;|$)", line):
            for v in ("0", "1"):
                out.append((i, f"ret {v}", lines[i][:m.end()] + " " + v + lines[i][m.end():]))
        if not STRUCTURE.match(line):
            out.append((i, "del", ""))
        out += classifier(lines, i, line)
    return out


def classifier(lines: list[str], i: int, line: str) -> list[tuple[int, str, str]]:
    """The alt, glob, anch, quant, word, flag, pipe, src and copy rules on one line."""
    out: list[tuple[int, str, str]] = []
    orig = lines[i]

    def put(rule: str, a: int, b: int, text: str) -> None:
        out.append((i, rule, orig[:a] + text + orig[b:]))

    m = LABEL.match(line)
    if m and not line.lstrip().startswith("case "):
        a, label = m.start(2), m.group(2)
        alts = label.split("|")
        if len(alts) > 1:
            for k in range(len(alts)):
                put(f"alt {alts[k]}", a, a + len(label), "|".join(alts[:k] + alts[k + 1:]))
        for k, ch in enumerate(label):
            if ch == "?":
                put(f"glob ?{k}->0", a + k, a + k + 1, "0")
        for g in re.finditer(r"\?\*", label):
            put("glob ?*->*", a + g.start(), a + g.end(), "*")
    for p in PATTERN.finditer(line):
        a, pat = p.start(3), p.group(3)
        alts = pat.split("|")
        if len(alts) > 1:
            for k in range(len(alts)):
                put(f"alt {alts[k]!r}", a, a + len(pat), "|".join(alts[:k] + alts[k + 1:]))
        for k, ch in enumerate(pat):
            if ch in "^$":
                put(f"anch {ch}@{k}", a + k, a + k + 1, "")
            if ch in "?*" and k and pat[k - 1] != "\\":
                put(f"quant {ch}@{k}", a + k, a + k + 1, "")
        words = pat.split(" ")
        if re.fullmatch(r"[A-Za-z]+( [A-Za-z]+)+", pat):
            for k in range(len(words)):
                put(f"word -{words[k]}", a, a + len(pat), " ".join(words[:k] + words[k + 1:]))
        fa, flags = p.start(2), p.group(2)
        for k in range(len(flags)):
            rest = flags[:k] + flags[k + 1:]
            if rest:
                put(f"flag -{flags[k]}", fa, fa + len(flags), rest)
            else:
                put(f"flag -{flags[k]}", fa - 2, fa + len(flags), "")
    for t in re.finditer(r" \| tail (-\d+)", line):
        put("pipe tail->head", t.start(), t.end(), f" | head {t.group(1)}")
        put("pipe -tail", t.start(), t.end(), "")
    for c in re.finditer(r'"\$\(cat "(\$\w+)"\)"', line):
        for v in sorted({m2.group(1) for l in lines[region(lines).start:region(lines).stop]
                         if f'< "{c.group(1)}"' in l
                         for m2 in [re.match(r"\s*(\w+)=", l)] if m2}):
            put(f"src ->${v}", c.start(), c.end(), f'"${v}"')
    operands = sorted({m2.group(1) for l in lines[region(lines).start:region(lines).stop]
                       for m2 in FEED.finditer(code(l))})
    for f in FEED.finditer(line):
        for cut in ("tail -1", "head -1"):
            put(f"copy +{cut}", f.end(1), f.end(1), f" | {cut}")
        for v in operands:
            if v != f.group(1):
                put(f"copy ->{v}", f.start(1), f.end(1), v)
    return out


