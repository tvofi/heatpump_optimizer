#!/usr/bin/env python3
"""R10-FLY-GH-READ-RETRY: every one-line mutant of app_approve.sh's retry path, against its self-test.

    python3 dev/audit/harnesses/r10_gh_read_retry_mutants.py            # all
    python3 dev/audit/harnesses/r10_gh_read_retry_mutants.py --list     # enumerate only
    python3 dev/audit/harnesses/r10_gh_read_retry_mutants.py M0 M17     # named

Run from the branch's worktree with its work committed. The region is
`tools/pr/app_approve.sh` from `READ_TRIES=` to the `}` closing `gh_read()`:
the budget, the schedule, the classifier and the loop. The mutants are not
hand-picked; each is generated by one rule applied to one line of the region:

  num   every integer literal outside a comment and a descriptor (`2>`, `>&2`)
        -> n-1 (when >= 0), n+1, 999
  rel   every `-ge -gt -le -lt -eq -ne` -> each of the other five
  opnd  every `"$var"` operand of such a test -> 999 (the review's unbounded
        `[ "$_try" -ge 999 ]` is this rule's)
  or    every `||` -> `&&`, every `&&` -> `||`
  not   every `if !` -> `if`
  ret   every bare `return` -> `return 0` and `return 1`
  del   every non-comment line that is not pure structure (`{ } fi done esac`,
        `case ... in`, `while ...; do`, a function header) is deleted

so a bound, budget or classification branch added to the region is swept the
day it lands, with no edit here. M0 is the unmutated head and must pass.

Each mutant runs `bash tools/pr/app_approve.sh --self-test` in one of
`--jobs N` (default 4) detached worktrees of HEAD, which are removed
afterwards; the branch's own tree is never edited. A mutant is KILLED when the
self-test exits non-zero; SURVIVED otherwise. A survivor that is equivalent by
construction is listed in EQUIVALENT with the reason, and reads EQUIVALENT;
every other survivor is an unpinned branch. An EQUIVALENT entry that no rule
generates any more refuses the run.

Prints one line per mutant, then `RESULT mutants=<n> killed=<k>
equivalent=<e> survivors=<s>`; exits 1 when any survived or M0 failed.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from queue import Queue

ROOT = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"],
                           capture_output=True, text=True, check=True).stdout.strip())
TARGET = "tools/pr/app_approve.sh"

# Survivors no self-test can kill, each keyed on (line text, mutated text).
NONZERO = "every caller tests zero against non-zero only (`|| die`, `if !`)"
EQUIVALENT: dict[tuple[str, str], str] = {
    ('GH_ERR=""', ""): "its one reader is a caller's die after gh_read returned 1, and every return-1 path assigns GH_ERR first",
    ("  local code", ""): "scope only: no other line of the file names a variable `code` (grep -nw code)",
    ("    ?*) return 1 ;;", "    ?*) return 2 ;;"): NONZERO,
    ("    ?*) return 1 ;;", "    ?*) return 999 ;;"): NONZERO,
    ("    ?*) return 1 ;;", ""): "a status line falls through to the transport grep, which no `gh: ... (HTTP NNN)` line matches; "
                                 "the two differ only for one stderr holding a status and a transport line, and a transport failure carries no status",
    ('  _ef=$(mktemp "${TMPDIR:-/tmp}/app_approve_read.XXXXXX") || { GH_ERR="could not create a temporary file"; return 1; }',
     '  _ef=$(mktemp "${TMPDIR:-/tmp}/app_approve_read.XXXXXX") || { GH_ERR="could not create a temporary file"; return 2; }'): NONZERO,
    ('  _ef=$(mktemp "${TMPDIR:-/tmp}/app_approve_read.XXXXXX") || { GH_ERR="could not create a temporary file"; return 1; }',
     '  _ef=$(mktemp "${TMPDIR:-/tmp}/app_approve_read.XXXXXX") || { GH_ERR="could not create a temporary file"; return 999; }'): NONZERO,
    ('    if ! gh_transient "$(cat "$_ef")" || [ "$_try" -ge "$READ_TRIES" ]; then',
     '    if ! gh_transient "$(cat "$_ef")" || [ "$_try" -eq "$READ_TRIES" ]; then'):
        "_try starts at 1 and steps by 1, so it equals READ_TRIES (>= 1) before it can exceed it",
    ('      [ "$_try" -eq 1 ] || GH_ERR="$GH_ERR (after $_try attempts)"',
     '      [ "$_try" -le 1 ] || GH_ERR="$GH_ERR (after $_try attempts)"'): "_try is never below 1",
    ("      return 1", "      return 2"): NONZERO,
    ("      return 1", "      return 999"): NONZERO,
}

STRUCTURE = re.compile(r"^\s*(\{|\}|fi|done|esac|case .* in|while .*; do|[a-z_]+\(\) \{.*)\s*$")
NUM = re.compile(r"(?<![\w$\\.&-])(\d+)(?![\w>])")
REL = ["-ge", "-gt", "-le", "-lt", "-eq", "-ne"]


def region(lines: list[str]) -> range:
    start = next(i for i, l in enumerate(lines) if l.startswith("READ_TRIES="))
    head = next(i for i in range(start, len(lines)) if lines[i].startswith("gh_read() {"))
    end = next(i for i in range(head, len(lines)) if lines[i] == "}")
    return range(start, end + 1)


def code(line: str) -> str:
    """The line up to an inline comment: a ` # ` with no quote open before it."""
    for m in re.finditer(r"\s#\s", line):
        pre = line[:m.start()]
        if pre.count("'") % 2 == 0 and pre.count('"') % 2 == 0:
            return pre
    return line


def mutants(lines: list[str]) -> list[tuple[int, str, str]]:
    """(line index, rule, mutated line) for every rule application in the region."""
    out: list[tuple[int, str, str]] = []
    for i in region(lines):
        line = code(lines[i])
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        for m in NUM.finditer(line):
            n = int(m.group(1))
            for v in ([n - 1] if n > 0 else []) + [n + 1, 999]:
                out.append((i, f"num {n}->{v}", lines[i][:m.start()] + str(v) + lines[i][m.end():]))
        for m in re.finditer(r"(?<=\s)-(ge|gt|le|lt|eq|ne)(?=\s)", line):
            for op in REL:
                if op != m.group(0):
                    out.append((i, f"rel {m.group(0)}->{op}", lines[i][:m.start()] + op + lines[i][m.end():]))
        for m in re.finditer(r'"\$\w+"(?= -(?:ge|gt|le|lt|eq|ne) )|(?<=-(?:ge|gt|le|lt|eq|ne) )"\$\w+"', line):
            out.append((i, f"opnd {m.group(0)}->999", lines[i][:m.start()] + "999" + lines[i][m.end():]))
        for m in re.finditer(r"\|\||&&", line):
            alt = "&&" if m.group(0) == "||" else "||"
            out.append((i, f"or {m.group(0)}->{alt}", lines[i][:m.start()] + alt + lines[i][m.end():]))
        for m in re.finditer(r"\bif ! ", line):
            out.append((i, "not", lines[i][:m.start()] + "if " + lines[i][m.end():]))
        for m in re.finditer(r"\breturn(?= ;|;|$)", line):
            for v in ("0", "1"):
                out.append((i, f"ret {v}", lines[i][:m.end()] + " " + v + lines[i][m.end():]))
        if not STRUCTURE.match(line):
            out.append((i, "del", ""))
    return out


def selftest(tree: Path) -> tuple[int, str]:
    p = subprocess.run(["bash", TARGET, "--self-test"], cwd=tree, capture_output=True, text=True)
    summary = next((l for l in reversed(p.stdout.splitlines()) if "self-test:" in l), "no summary line")
    fails = [l[5:] for l in p.stdout.splitlines() if l.startswith("FAIL ")]
    return p.returncode, summary + ("; first FAIL: " + fails[0] if fails else "")


def main(argv: list[str]) -> int:
    jobs = 4
    if "--jobs" in argv:
        k = argv.index("--jobs"); jobs = int(argv[k + 1]); del argv[k:k + 2]
    base = (ROOT / TARGET).read_text()
    lines = base.split("\n")
    table = {f"M{n}": m for n, m in enumerate(mutants(lines), start=1)}
    table["M0"] = (-1, "null", "")
    generated = {(lines[i], new) for i, _, new in table.values() if i >= 0}
    stale = [k for k in EQUIVALENT if k not in generated]
    if stale:  # an entry no rule generates any more would excuse nothing, silently
        print(f"EQUIVALENT entries no rule generates: {stale}")
        return 1
    names = [a for a in argv if not a.startswith("--")] or ["M0"] + [f"M{n}" for n in range(1, len(table))]
    if "--list" in argv:
        for name in names:
            i, rule, new = table[name]
            print(f"{name}\t{i + 1 if i >= 0 else '-'}\t{rule}\t{new!r}")
        return 0
    trees: Queue[Path] = Queue()
    tmp = Path(tempfile.mkdtemp(prefix="ghretry-mut-"))
    for j in range(jobs):
        t = tmp / f"w{j}"
        subprocess.run(["git", "worktree", "add", "--detach", "-q", str(t), "HEAD"], cwd=ROOT, check=True)
        trees.put(t)

    def one(name: str) -> tuple[str, str]:
        i, rule, new = table[name]
        t = trees.get()
        try:
            text = lines[:]
            if i >= 0:
                if rule == "del":
                    del text[i]
                else:
                    text[i] = new
            (t / TARGET).write_text("\n".join(text))
            rc, summary = selftest(t)
            (t / TARGET).write_text(base)
        finally:
            trees.put(t)
        where = "" if i < 0 else f" l.{i + 1} {rule}: {lines[i].strip()!r}" + ("" if rule == "del" else f" -> {new.strip()!r}")
        if name == "M0":
            verdict = "NULL-OK" if rc == 0 else "NULL-FAILED"
        elif rc != 0:
            verdict = "KILLED"
        elif (lines[i], new) in EQUIVALENT:
            verdict = "EQUIVALENT (" + EQUIVALENT[(lines[i], new)] + ")"
        else:
            verdict = "SURVIVED"
        return name, f"{name} {verdict}{where} | rc={rc} {summary}"

    try:
        with ThreadPoolExecutor(jobs) as ex:
            results = dict(ex.map(one, names))
    finally:
        for j in range(jobs):
            subprocess.run(["git", "worktree", "remove", "--force", str(tmp / f"w{j}")], cwd=ROOT)
        shutil.rmtree(tmp, ignore_errors=True)
    for name in names:
        print(results[name])
    rows = [results[n] for n in names if n != "M0"]
    k = sum(" KILLED" in r for r in rows)
    e = sum(" EQUIVALENT" in r for r in rows)
    s = sum(" SURVIVED" in r for r in rows)
    print(f"RESULT mutants={len(rows)} killed={k} equivalent={e} survivors={s}")
    null_bad = "M0" in results and "NULL-FAILED" in results["M0"]
    return 1 if s or null_bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
